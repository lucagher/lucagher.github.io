/**
 * Generate client-side credential hashes from local environment variables.
 * Output file: Datachallenge/assets/credential-hashes.js
 *
 * This script NEVER writes plaintext secrets, only SHA-256 hashes.
 * It reads the following environment variables (from your shell or .env):
 *  - TEAM1_PASSWORD ... TEAM5_PASSWORD
 *  - ADMIN_PASSWORD
 *
 * Usage:
 *   # For local only (Mac/Linux), create .env and run:
 *   node tools/generate-credential-hashes.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

// Simple .env loader (no external deps)
function loadDotEnvIfPresent() {
  try {
    const envPath = resolve(process.cwd(), '.env');
    const raw = readFileSync(envPath, 'utf8');
    raw.split(/\r?\n/).forEach((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) return;
      const idx = trimmed.indexOf('=');
      if (idx === -1) return;
      const key = trimmed.slice(0, idx).trim();
      let val = trimmed.slice(idx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!(key in process.env)) {
        process.env[key] = val;
      }
    });
  } catch {
    // .env absent is fine
  }
}

function sha256Hex(str) {
  return createHash('sha256').update(str, 'utf8').digest('hex');
}

loadDotEnvIfPresent();

const teamPasswords = {
  aau26_team1: process.env.TEAM1_PASSWORD || '',
  aau26_team2: process.env.TEAM2_PASSWORD || '',
  aau26_team3: process.env.TEAM3_PASSWORD || '',
  aau26_team4: process.env.TEAM4_PASSWORD || '',
  aau26_team5: process.env.TEAM5_PASSWORD || '',
};

const adminPassword = process.env.ADMIN_PASSWORD || '';
const githubToken = process.env.SECRET_TOKEN || '';
const supabaseUrl = process.env.SUPABASE_URL || '';
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || '';

// Validate presence (optional warnings)
const missing = Object.entries(teamPasswords)
  .filter(([, v]) => !v)
  .map(([k]) => k);
if (!adminPassword) missing.push('ADMIN_PASSWORD');
if (!githubToken) missing.push('SECRET_TOKEN');
if (!supabaseUrl) missing.push('SUPABASE_URL');
if (!supabaseAnonKey) missing.push('SUPABASE_ANON_KEY');
if (missing.length) {
  console.warn('[WARN] Missing env variables:', missing.join(', '));
}

const teamNames = {
  aau26_team1: 'P-value pirates',
  aau26_team2: 'The Rvengers',
  aau26_team3: 'Outliers',
  aau26_team4: 'Smooth operators',
  aau26_team5: 'Byte me',
};

const output = {
  teams: Object.fromEntries(
    Object.entries(teamPasswords).map(([teamId, pw]) => [
      teamId,
      {
        passwordHash: pw ? sha256Hex(pw) : '',
        teamName: teamNames[teamId],
      },
    ])
  ),
  competitions: {
    fitbit: {
      passwordHash: adminPassword ? sha256Hex(adminPassword) : '',
    },
  },
  github: {
    token: githubToken || '',
    repo: process.env.GITHUB_REPO || 'lucagher/lucagher.github.io',
  },
  supabase: {
    url: supabaseUrl || '',
    anonKey: supabaseAnonKey || '',
  },
};

const outPath = resolve(process.cwd(), 'Datachallenge/assets/credential-hashes.js');
const header = '/* Generated by tools/generate-credential-hashes.mjs — DO NOT COMMIT */\n';
const body = `window.CREDENTIAL_HASHES = ${JSON.stringify(output, null, 2)};\n`;

writeFileSync(outPath, header + body, 'utf8');
console.log('[OK] Wrote', outPath);


